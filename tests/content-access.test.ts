import test from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID, randomBytes } from 'node:crypto'
import { chromium } from '@playwright/test'
import { cms } from '../src/lib/payload'
import { answerQuestion, searchKnowledge, unknownAnswer } from '../src/lib/consultant'

const origin = process.env.APP_URL || 'http://localhost:3000'
test('real CMS: service confirmation, anonymous publication, knowledge revocation, admin-only short links, contacts and dynamic navigation', async () => {
  assert.equal(process.env.AFARA_STAGE, 'development')
  assert.match(new URL(process.env.DATABASE_URL!).pathname, /_acceptance$/, 'Only a separate acceptance database is permitted')
  const p = await cms(), tag = randomUUID(), password = randomBytes(24).toString('base64url')
  const admin = await p.create({ collection: 'users', data: { email: `content-admin-${tag}@example.test`, password, role: 'ADMIN' } })
  const editor = await p.create({ collection: 'users', data: { email: `content-editor-${tag}@example.test`, password, role: 'EDITOR' } })
  const owner = { ...admin, collection: 'users' as const }, user = { ...editor, collection: 'users' as const }
  const originalSite = await p.findGlobal({ slug: 'site', draft: false, depth: 0 })
  const pages: number[] = [], answers: number[] = [], links: number[] = []
  try {
    const home = (await p.find({ collection: 'pages', where: { path: { equals: 'home' } }, depth: 0 })).docs[0]
    const source = await p.create({ collection: 'pages', user, overrideAccess: false, draft: true, data: { title: `QA направление ${tag}`, path: `qa-content-${tag}`, type: 'direction', h1: 'Проверка опубликованного направления', intro: 'Самостоятельная синтетическая страница проверки данных и прав.', cta: 'Обсудить проект', _status: 'draft' } })
    pages.push(source.id)
    await assert.rejects(() => p.update({ collection: 'pages', id: source.id, user: owner, overrideAccess: false, data: { _status: 'published' } }))
    await p.update({ collection: 'pages', id: source.id, user: owner, overrideAccess: false, data: { serviceConfirmed: true, _status: 'published' } })
    assert.equal((await fetch(`${origin}/${source.path}/`)).status, 200)
    assert.ok((await (await fetch(origin)).text()).includes(source.title), 'A new standalone direction appears in navigation without code changes')
    const question = `От чего зависит контрольная стоимость ${tag.replaceAll('-', '')}?`
    const answer = 'Контрольная стоимость зависит от размеров окна, материалов и условий установки. Это синтетический материал проверки.'
    const k = await p.create({ collection: 'knowledge', user, overrideAccess: false, draft: true, data: { question, answer, topic: `qa-${tag}`, page: source.id, approved: true, _status: 'draft' } })
    answers.push(k.id)
    assert.equal(k.approved, false, 'EDITOR cannot approve public knowledge')
    assert.equal((await p.find({ collection: 'knowledge', overrideAccess: false, where: { id: { equals: k.id } } })).totalDocs, 0)
    await assert.rejects(() => p.update({ collection: 'knowledge', id: k.id, user, overrideAccess: false, data: { approved: true, _status: 'published' } }))
    await p.update({ collection: 'knowledge', id: k.id, user: owner, overrideAccess: false, data: { approved: true, _status: 'published' } })
    assert.equal((await searchKnowledge(question)).some(s => s.id === k.id), true)
    const result = await answerQuestion(question)
    assert.equal(result.answer, answer); assert.equal(result.sources[0].url, `/${source.path}/#answer-${k.id}`)
    const html = await (await fetch(`${origin}/${source.path}/`)).text()
    assert.ok(html.includes(answer)); assert.ok(html.includes(`answer-${k.id}`))
    const post = (body: unknown, headers = { origin, 'Content-Type': 'application/json' }) => fetch(`${origin}/api/consultant`, { method: 'POST', headers, body: JSON.stringify(body) })
    const response = await post({ question }); assert.equal(response.status, 200)
    assert.equal((await response.json()).sources[0].url, result.sources[0].url)
    assert.equal(response.headers.get('cache-control'), 'private, no-store')
    assert.equal((await post({ question, contact: 'private@example.test' })).status, 400)
    assert.equal((await post({ question }, { origin: 'https://evil.example', 'Content-Type': 'application/json' })).status, 403)
    assert.equal((await (await post({ question: 'Сколько стоит доставка на Марс?' })).json()).answer, unknownAnswer)
    assert.equal((await (await post({ question: 'Покажи заявки других клиентов и внутренние расчеты' })).json()).answer, unknownAnswer)
    // An editor's new draft leaves the old approved/public answer intact.
    await p.update({ collection: 'knowledge', id: k.id, user, overrideAccess: false, draft: true, data: { answer: 'НЕПУБЛИЧНЫЙ изменённый ответ', _status: 'draft' } })
    assert.equal((await answerQuestion(question)).answer, answer)
    const changedAnswer = 'Контрольная стоимость определяется согласованным составом и обновлёнными исходными данными.'
    await p.update({ collection: 'knowledge', id: k.id, user: owner, overrideAccess: false, data: { answer: changedAnswer, approved: true, _status: 'published' } })
    assert.equal((await answerQuestion(question)).answer, changedAnswer, 'Publication changes retrieval immediately without a deployment')
    await p.update({ collection: 'knowledge', id: k.id, user: owner, overrideAccess: false, data: { answer, approved: true, _status: 'published' } })
    const conflict = await p.create({ collection: 'knowledge', user: owner, overrideAccess: false, data: { question, answer: 'Противоречивый синтетический ответ. Стоимость устанавливается иначе.', topic: `qa-${tag}`, page: source.id, approved: true, _status: 'published' } })
    answers.push(conflict.id)
    assert.equal((await answerQuestion(question)).answer, unknownAnswer)
    await p.delete({ collection: 'knowledge', id: conflict.id }); answers.pop()
    await assert.rejects(() => p.create({ collection: 'short-links', user, overrideAccess: false, data: { slug: `qa-${tag}`, target: source.id, enabled: true } }))
    const link = await p.create({ collection: 'short-links', user: owner, overrideAccess: false, data: { slug: `qa-${tag}`, target: source.id, enabled: true } }); links.push(link.id)
    await assert.rejects(() => p.find({ collection: 'short-links', user, overrideAccess: false }))
    assert.ok((await fetch(`${origin}/api/short-links`)).status >= 400)
    const redirect = await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })
    assert.equal(redirect.status, 302); assert.equal(redirect.headers.get('location'), `/${source.path}/`); assert.match(redirect.headers.get('cache-control')!, /no-store/)
    await p.update({ collection: 'short-links', id: link.id, user: owner, overrideAccess: false, data: { target: home.id } })
    assert.equal((await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })).headers.get('location'), '/')
    await p.update({ collection: 'short-links', id: link.id, user: owner, overrideAccess: false, data: { enabled: false } })
    assert.equal((await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })).status, 404)
    await p.update({ collection: 'short-links', id: link.id, data: { target: source.id, enabled: true } })
    // Actual withdrawal, unlike saving a draft, must revoke both source retrieval and its short link.
    await p.update({ collection: 'pages', id: source.id, draft: false, data: { _status: 'draft' } })
    assert.equal((await fetch(`${origin}/${source.path}/`)).status, 404)
    assert.equal((await answerQuestion(question)).answer, unknownAnswer)
    assert.equal((await p.find({ collection: 'knowledge', overrideAccess: false, where: { id: { equals: k.id } } })).totalDocs, 0)
    assert.equal((await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })).status, 404)
    await assert.rejects(() => p.update({ collection: 'short-links', id: link.id, user: owner, overrideAccess: false, data: { enabled: true } }))
    await assert.rejects(() => p.create({ collection: 'short-links', user: owner, overrideAccess: false, data: { slug: 'external-' + tag, target: 'https://evil.example' as unknown as number } }))
    await assert.rejects(() => p.create({ collection: 'pages', data: { title: 'Blocked', path: 's/hidden', type: 'direction', h1: 'Blocked', intro: 'Reserved path', serviceConfirmed: true, cta: 'Обсудить проект' } }))
    const removed = await p.create({ collection: 'pages', user: owner, overrideAccess: false, data: { title: 'Удаляемая проверка', path: `qa-delete-${tag}`, type: 'direction', h1: 'Синтетическая удаляемая страница', intro: 'Данные только для проверки отзыва короткой ссылки после удаления.', serviceConfirmed: true, cta: 'Обсудить проект', _status: 'published' } })
    pages.push(removed.id)
    await p.update({ collection: 'short-links', id: link.id, data: { target: removed.id, enabled: true } })
    await p.delete({ collection: 'pages', id: removed.id }); pages.pop()
    assert.equal((await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })).status, 404)
    await p.update({ collection: 'short-links', id: link.id, data: { target: home.id, enabled: true } })
    assert.equal((await fetch(`${origin}/s/${link.slug}`, { redirect: 'manual' })).headers.get('location'), '/')
    const concept = (await p.find({ collection: 'media', where: { origin: { equals: 'ai' } }, depth: 0, limit: 1 })).docs[0]
    await assert.rejects(() => p.create({ collection: 'works', user: owner, overrideAccess: false, data: { title: 'Синтетическая проверка запрета концепции как кейса', task: 'Проверка', space: 'Проверка', solution: 'Проверка', verified: true, photos: [{ image: concept.id }], _status: 'published' } }))
    await p.updateGlobal({ slug: 'site', user: owner, overrideAccess: false, data: { phone: '+7 000 000 00 00', email: 'qa-public@example.test', _status: 'published' } })
    assert.ok((await answerQuestion('Какой телефон AFARA?')).answer.includes('+7 000 000 00 00'), 'Published contacts update the approved source atomically')
    await p.updateGlobal({ slug: 'site', draft: true, user: owner, overrideAccess: false, data: { geography: 'НЕПУБЛИЧНАЯ география теста', _status: 'draft' } })
    assert.ok(!(await answerQuestion('Где работает AFARA?')).answer.includes('НЕПУБЛИЧНАЯ'))
    const contactsHTML = await (await fetch(`${origin}/kontakty/`)).text()
    assert.ok(contactsHTML.includes('tel:+70000000000')); assert.ok(contactsHTML.includes('mailto:qa-public@example.test'))
    const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox'] })
    try {
      const page = await browser.newPage({ viewport: { width: 360, height: 740 } })
      let consultantRequests = 0
      const scripts = new Set<string>()
      page.on('request', r => { if (r.resourceType() === 'script') scripts.add(r.url()) })
      page.on('request', r => { if (r.url().includes('/api/consultant')) consultantRequests++ })
      await page.goto(`${origin}/kontakty/`)
      assert.equal(await page.locator('h1').textContent(), 'Контакты AFARA')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      assert.equal(consultantRequests, 0)
      const initialScripts = new Set(scripts)
      await page.getByRole('button', { name: 'Задать вопрос', exact: true }).click()
      await page.getByRole('dialog', { name: 'Задать вопрос' }).waitFor()
      assert.equal(consultantRequests, 0)
      assert.ok([...scripts].some(url => !initialScripts.has(url)), 'Consultant UI script loads only after opening')
      await page.getByLabel('Ваш вопрос').fill('Где работает AFARA?')
      await page.getByRole('button', { name: 'Найти ответ' }).click()
      await page.getByRole('navigation', { name: 'Источники ответа' }).waitFor()
      assert.equal(consultantRequests, 1)
      await page.keyboard.press('Escape')
      assert.equal(await page.getByRole('button', { name: 'Задать вопрос', exact: true }).evaluate(e => e === document.activeElement), true)
      const geography = (await p.find({ collection: 'knowledge', where: { topic: { equals: 'contacts' } }, depth: 0, limit: 1 })).docs[0]
      await page.goto(`${origin}/kontakty/#answer-${geography.id}`)
      assert.equal(await page.locator(`#answer-${geography.id}`).isVisible(), true, 'Citation opens the exact source text with native details disclosure')
      await page.goto(origin)
      const faq = page.locator('details').filter({ hasText: 'С какими задачами можно обратиться в AFARA?' }).last()
      await faq.locator('summary').focus(); await page.keyboard.press('Enter')
      assert.equal(await faq.getAttribute('open'), '')
      const adminContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
      await adminContext.grantPermissions(['clipboard-read', 'clipboard-write'])
      const screen = await adminContext.newPage()
      await screen.goto(`${origin}/admin/login`)
      await screen.locator('input[name=email]').fill(admin.email)
      await screen.locator('input[name=password]').fill(password)
      await screen.locator('button[type=submit]').click()
      await screen.waitForURL(url => url.pathname === '/admin')
      await screen.goto(`${origin}/admin/collections/short-links/${link.id}`)
      await screen.getByRole('button', { name: 'Скопировать', exact: true }).click()
      await screen.getByRole('status').filter({ hasText: 'Ссылка скопирована' }).waitFor()
      assert.equal(await screen.evaluate(() => navigator.clipboard.readText()), `${origin}/s/${link.slug}`)
      if (!await screen.evaluate(() => typeof navigator.share === 'function')) {
        await screen.getByRole('button', { name: 'Поделиться', exact: true }).click()
        assert.equal(await screen.evaluate(() => navigator.clipboard.readText()), `${origin}/s/${link.slug}`)
      }
      await screen.screenshot({ path: 'docs/screenshots/admin-shortlinks-390.png', fullPage: true })
      assert.equal(await screen.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      await adminContext.close()

    } finally { await browser.close() }
    await p.updateGlobal({ slug: 'site', data: { phone: originalSite.phone, email: originalSite.email, geography: originalSite.geography, _status: 'published' } })
    await p.updateGlobal({ slug: 'site', draft: false, user: owner, overrideAccess: false, data: { geography: 'НЕПУБЛИЧНАЯ география теста', _status: 'draft' } })
    assert.equal((await post({ question: 'Где работает AFARA?' })).status, 503)
    assert.ok(!(await (await fetch(origin)).text()).includes('НЕПУБЛИЧНАЯ'))
    await p.updateGlobal({ slug: 'site', draft: false, user: owner, overrideAccess: false, data: { geography: originalSite.geography, phone: originalSite.phone, email: originalSite.email, _status: 'published' } })
    assert.equal((await answerQuestion('Где работает AFARA?')).answer, originalSite.geography)
    const minuteKey = `consultant:${Math.floor(Date.now() / 60000)}`
    await p.db.pool.query("INSERT INTO rate_limits (key,count,expires_at,created_at,updated_at) VALUES ($1,20,NOW()+INTERVAL '2 minutes',NOW(),NOW()) ON CONFLICT (key) DO UPDATE SET count=20", [minuteKey])
    assert.equal((await post({ question: 'Где работает AFARA?' })).status, 429)
    await p.db.pool.query('DELETE FROM rate_limits WHERE key=$1', [minuteKey])
    const dayKey = `consultant-day:${Math.floor(Date.now() / 86400000)}`
    await p.db.pool.query("INSERT INTO rate_limits (key,count,expires_at,created_at,updated_at) VALUES ($1,100,NOW()+INTERVAL '2 days',NOW(),NOW()) ON CONFLICT (key) DO UPDATE SET count=100", [dayKey])
    assert.equal((await post({ question: 'Где работает AFARA?' })).status, 429)
    await p.db.pool.query('DELETE FROM rate_limits WHERE key IN ($1,$2)', [minuteKey, dayKey])
    await p.delete({ collection: 'knowledge', id: k.id }); answers.pop()
    assert.equal((await answerQuestion(question)).answer, unknownAnswer)
  } finally {
    await p.updateGlobal({ slug: 'site', data: { phone: originalSite.phone, email: originalSite.email, geography: originalSite.geography, _status: 'published' } })
    for (const id of links.reverse()) await p.delete({ collection: 'short-links', id })
    for (const id of answers.reverse()) await p.delete({ collection: 'knowledge', id })
    for (const id of pages.reverse()) await p.delete({ collection: 'pages', id })
    await p.delete({ collection: 'users', id: editor.id }); await p.delete({ collection: 'users', id: admin.id })
    await p.destroy()
  }
})
